#ifndef ASM330LHHXTR_H
#define ASM330LHHXTR_H

#include "spi.h"

#define ASM330LHHXTR_SPI_BUS hspi3

#define ASM330LHHXTR_CS_GPIO_PORT GPIOD
#define ASM330LHHXTR_CS_PIN GPIO_PIN_1

#define ASM330LHHXTR_READ_BIT 0x80
#define ASM330LHHXTR_WRITE_BIT 0x7F

#define ASM330LHHXTR_WHO_AM_I 0x0F
#define ASM330LHHXTR_WHO_AM_I_VALUE 0x6B
#define ASM330LHHXTR_CTRL1_XL 0x10
#define ASM330LHHXTR_CTRL1_XL_VALUE 0xA4 // 6667 Hz, +/- 16g, LPF2 disabled
#define ASM330LHHXTR_CTRL2_G 0x11
#define ASM330LHHXTR_CTRL2_G_VALUE 0xA1 // 6667 Hz, +/- 4000 dps
#define ASM330LHHXTR_CTRL3_C 0x12
#define ASM330LHHXTR_CTRL3_C_VALUE (1 << 6) | (1 << 2) // BDU = 1, IF_INC = 1
#define ASM330LHHXTR_CTRL4_C 0x13
#define ASM330LHHXTR_CTRL5_C 0x14
#define ASM330LHHXTR_CTRL6_C 0x15
#define ASM330LHHXTR_CTRL7_G 0x16
#define ASM330LHHXTR_CTRL8_XL 0x17
#define ASM330LHHXTR_CTRL9_XL 0x18
#define ASM330LHHXTR_CTRL10_C 0x19
#define ASM330LHHXTR_STATUS_REG 0x1E
#define ASM330LHHXTR_STATUS_REG_TEMP_READY (1 << 0)
#define ASM330LHHXTR_STATUS_REG_GYRO_READY (1 << 1)
#define ASM330LHHXTR_STATUS_REG_ACCEL_READY (1 << 2)
#define ASM330LHHXTR_OUT_TEMP_L 0x20
#define ASM330LHHXTR_OUTX_L_G 0x22
#define ASM330LHHXTR_OUTX_L_A 0x28

typedef struct {
	float temp;
	float gx, gy, gz;
	float ax, ay, az;
} ASM330LHHXTR_Data;

HAL_StatusTypeDef ASM330LHHXTR_ReadRegister(uint8_t REGISTER_ADDRESS, uint8_t *data, uint16_t length);
HAL_StatusTypeDef ASM330LHHXTR_WriteRegister(uint8_t REGISTER_ADDRESS, uint8_t value);
HAL_StatusTypeDef ASM330LHHXTR_Verify(void);
HAL_StatusTypeDef ASM330LHHXTR_Init(void);
HAL_StatusTypeDef ASM330LHHXTR_ReadData(ASM330LHHXTR_Data *data);

#endif
